"""TC-FVT-023 extension: live Slurm traffic path over IPoIB.

Captures Slurm TCP traffic on a compute node during a 2-node job and requires
every Slurm packet to use the IB interface in the address family Slurm
NodeAddr resolves to for the active ib_addr_mode (IPv4 for ipv4-only, IPv6 for
ipv6-only and dual-stack). Any packet on the admin Ethernet or in the other
family is a failure.
"""

import re
import shlex
import time
from typing import Any

from ..vars.ipoib_vars import (
    IB_MODE_FAMILIES,
    IPOIB_COMM_CAPTURE_TIMEOUT,
    IPOIB_COMM_JOB_SLEEP,
    IPOIB_COMM_PATH_COMMANDS,
    IPOIB_COMM_SETTLE_SECONDS,
    IPOIB_COMM_V4_PCAP,
    IPOIB_COMM_V6_PCAP,
    IPOIB_SLURM_PORT_SLURMCTLD,
    IPOIB_SLURM_PORT_SLURMD,
    IPOIB_SLURM_SRUN_PORT_RANGE,
)
from ..vars.pxeboot_vars import SLURM_COMPUTE_PREFIX, SLURM_CONTROL_PREFIX
from ._ipoib_helpers import slurm_family
from ._ipoib_runtime_helpers import ib_interface
from ._pxeboot_helpers import remote_command, runtime_exception, runtime_result
from ._workload_helpers import optional_skip
from .ipoib_pxeboot_func import _ipoib_nodes

_ERRORS = (OSError, RuntimeError, TypeError, ValueError, KeyError)

# tcpdump -i any text line: "<time> <iface> <In|Out> <IP|IP6> <src>.<port> > <dst>.<port>:"
_TCPDUMP_LINE = re.compile(
    r"^\S+\s+(\S+)\s+\S+\s+(IP6?)\s+"
    r"(\S+?)\.(\d+)\s+>\s+"
    r"(\S+?)\.(\d+):"
)

# Slurm channels seen from a compute node: (key, label, evidence required).
# slurmd and srun I/O traffic is always generated by a 2-node job; slurmctld
# traffic from the compute node depends on job-completion timing.
_CHANNELS: tuple[tuple[str, str, bool], ...] = (
    ("slurmd", f"slurmd ({IPOIB_SLURM_PORT_SLURMD})", True),
    ("srun", "srun I/O ({}-{})".format(*IPOIB_SLURM_SRUN_PORT_RANGE), True),
    ("slurmctld", f"slurmctld ({IPOIB_SLURM_PORT_SLURMCTLD})", False),
)


def _parse_tcpdump(output: str) -> list[dict[str, Any]]:
    """Parse tcpdump text output into flow records, ignoring loopback."""
    flows = []
    for line in output.splitlines():
        match = _TCPDUMP_LINE.match(line)
        if not match or match.group(1) == "lo":
            continue
        iface, kind, src_ip, src_port, dst_ip, dst_port = match.groups()
        flows.append({
            "interface": iface,
            "family": 6 if kind == "IP6" else 4,
            "src_ip": src_ip,
            "src_port": int(src_port),
            "dst_ip": dst_ip,
            "dst_port": int(dst_port),
        })
    return flows


def _channel(flow: dict[str, Any]) -> str:
    """Classify a flow (either direction) by the Slurm port it uses."""
    ports = (flow["src_port"], flow["dst_port"])
    if IPOIB_SLURM_PORT_SLURMCTLD in ports:
        return "slurmctld"
    if IPOIB_SLURM_PORT_SLURMD in ports:
        return "slurmd"
    low, high = IPOIB_SLURM_SRUN_PORT_RANGE
    if any(low <= port <= high for port in ports):
        return "srun"
    return ""


def _channel_stats(flows, ib_name: str, family: int) -> dict[str, dict[str, int]]:
    """Count, per channel, packets on IB in *family* and packets that violate it."""
    stats = {key: {"total": 0, "ok": 0, "off_ib": 0, "other_family": 0}
             for key, _label, _required in _CHANNELS}
    for flow in flows:
        key = _channel(flow)
        if not key:
            continue
        entry = stats[key]
        entry["total"] += 1
        on_ib = flow["interface"] == ib_name
        entry["off_ib"] += not on_ib
        entry["other_family"] += flow["family"] != family
        entry["ok"] += on_ib and flow["family"] == family
    return stats


def _evaluate(stats, ib_name: str, family: int) -> tuple[list[str], list[tuple[str, object]]]:
    """Return (failures, fields) for the per-channel traffic counts."""
    failures, fields = [], []
    for key, label, required in _CHANNELS:
        entry = stats[key]
        fields.append((
            label,
            f"{entry['total']} packets | IPv{family} on {ib_name}: {entry['ok']} | "
            f"off IB: {entry['off_ib']} | other family: {entry['other_family']}",
        ))
        if entry["off_ib"]:
            failures.append(f"{label}: {entry['off_ib']} packet(s) not on {ib_name}")
        if entry["other_family"]:
            failures.append(f"{label}: {entry['other_family']} packet(s) not IPv{family}")
        if required and not entry["total"]:
            failures.append(f"{label}: no packets captured; the path cannot be verified")
    return failures, fields


def _slurm_nodes(nodes):
    computes = [
        node for node in nodes
        if str(node["row"].get("EXPECTED_FUNCTIONAL_GROUP", "")).startswith(SLURM_COMPUTE_PREFIX)
    ]
    controller = next(
        (node for node in nodes
         if str(node["row"].get("EXPECTED_FUNCTIONAL_GROUP", "")).startswith(SLURM_CONTROL_PREFIX)),
        None,
    )
    return computes, controller


def _capture_job(host, cap_row, control_row, cap_host, peer_host):
    """Run a 2-node job under tcpdump on the capture node; return (job, v4, v6 output)."""
    v4_pcap, v6_pcap = IPOIB_COMM_V4_PCAP, IPOIB_COMM_V6_PCAP
    timeout_s = str(IPOIB_COMM_CAPTURE_TIMEOUT)
    try:
        start = remote_command(
            host, cap_row,
            IPOIB_COMM_PATH_COMMANDS["tcpdump_start"] % (
                shlex.quote(v4_pcap), shlex.quote(v6_pcap),
                timeout_s, shlex.quote(v4_pcap),
                timeout_s, shlex.quote(v6_pcap),
            ),
        )
        if "started" not in start.stdout:
            raise RuntimeError(f"Failed to start tcpdump on {cap_host}")
        time.sleep(IPOIB_COMM_SETTLE_SECONDS)
        job = remote_command(
            host, control_row,
            IPOIB_COMM_PATH_COMMANDS["srun_2node"] % (
                shlex.quote(cap_host), shlex.quote(peer_host), str(IPOIB_COMM_JOB_SLEEP),
            ),
        )
        if job.rc != 0:
            return job, "", ""
        time.sleep(IPOIB_COMM_CAPTURE_TIMEOUT - IPOIB_COMM_JOB_SLEEP)
        read = IPOIB_COMM_PATH_COMMANDS["tcpdump_read"]
        v4 = remote_command(host, cap_row, read % shlex.quote(v4_pcap)).stdout
        v6 = remote_command(host, cap_row, read % shlex.quote(v6_pcap)).stdout
        return job, v4, v6
    finally:
        remote_command(
            host, cap_row,
            IPOIB_COMM_PATH_COMMANDS["tcpdump_cleanup"]
            % (shlex.quote(v4_pcap), shlex.quote(v6_pcap)),
        )


def check_ipoib_slurm_comm_path(host) -> dict[str, Any]:
    """TC-FVT-023 ext: Slurm traffic uses IPoIB in the NodeAddr family, not Ethernet.

    1. Select two compute nodes holding the IB address Slurm uses for the mode.
    2. Capture Slurm ports (IPv4 and IPv6 separately) on one compute node.
    3. Run a 2-node srun job from the controller.
    4. Require every slurmd, srun I/O, and slurmctld packet to cross the
       capture node's IB interface in the expected family, and require
       slurmd and srun I/O packets to have been captured.
    """
    summary = "Slurm IPoIB communication path"
    try:
        mode, nodes = _ipoib_nodes(host)
        if mode not in IB_MODE_FAMILIES:
            return runtime_result(
                False, summary, [("IB mode", mode)], f"Unsupported ib_addr_mode {mode}"
            )
        family = slurm_family(mode)
        key = f"ipv{family}"
        computes, controller = _slurm_nodes(nodes)
        fields: list[tuple[str, object]] = [
            ("Mode", mode),
            ("Expected Slurm path", f"IPv{family} over IPoIB"),
            ("Controller", controller["row"]["HOSTNAME"] if controller else "none"),
        ]
        if controller is None:
            return optional_skip(summary, "No Slurm controller with IB_NIC_NAME is mapped")
        eligible = [node for node in computes if node[key]]
        if len(eligible) < 2:
            return optional_skip(
                summary, f"At least 2 Slurm compute nodes with IB IPv{family} are required"
            )
        capture, peer = eligible[0], eligible[1]
        cap_host, peer_host = capture["row"]["HOSTNAME"], peer["row"]["HOSTNAME"]
        _iface, ib_name = ib_interface(host, capture)
        fields.extend([
            ("Capture node", f"{cap_host} ({ib_name or 'no IB interface'} {capture[key]})"),
            ("Peer node", f"{peer_host} ({peer[key]})"),
        ])
        if not ib_name:
            return runtime_result(
                False, summary, fields, f"{cap_host} has no interface with its IB address"
            )
        if remote_command(host, capture["row"], IPOIB_COMM_PATH_COMMANDS["tcpdump_check"]).rc:
            return optional_skip(summary, f"tcpdump is not installed on {cap_host}")

        job, v4_out, v6_out = _capture_job(
            host, capture["row"], controller["row"], cap_host, peer_host
        )
        fields.append(("Job", "completed" if job.rc == 0 else f"FAILED rc={job.rc}"))
        if job.rc != 0:
            return runtime_result(
                False, summary, fields,
                f"srun job failed on {cap_host},{peer_host}: {job.stderr.strip()[:200]}",
            )
        flows = _parse_tcpdump(v4_out) + _parse_tcpdump(v6_out)
        failures, channel_fields = _evaluate(_channel_stats(flows, ib_name, family), ib_name, family)
        fields.extend(channel_fields)
        fields.append(("Result", f"all Slurm traffic IPv{family} over {ib_name}"
                       if not failures else "; ".join(failures)))
        return runtime_result(not failures, summary, fields, "; ".join(failures))
    except _ERRORS as exc:
        return runtime_exception(summary, exc)

def _job(name: str, stage: str, script: Sequence[str], conditions: Sequence[str],
         when: str = "on_success", needs: Optional[Sequence[str]] = None,
         optional: Sequence[str] = (), allow_failure: Optional[bool] = None,
         skip: Sequence[str] = (), id_tokens: bool = False,
         artifacts: Sequence[str] = (), variables: Optional[dict] = None,
         python_blocks: Sequence[str] = ()) -> List[str]:
    """Return the YAML lines of one job.

    ``skip`` lists the SKIP_STAGES words that skip it (default: the job name). SKIP_STAGES is a
    comma or space separated list and a word must match exactly, so ``telemetry`` skips the
    domain's jobs while ``test_cleanup_telemetry`` skips only that one.
    """
    lines = [f"{name}:", f"  stage: {stage}", "  timeout: 3h"]
    if allow_failure is not None:
        lines.append(f"  allow_failure: {str(allow_failure).lower()}")
    if variables:
        lines += ["  variables:"] + [_scalar(f"    {k}: ", v, "      ") for k, v in variables.items()]
    if id_tokens:
        lines += ["  id_tokens:", "    VAULT_ID_TOKEN:", "      aud: $BAO_SERVER_URL"]
    if needs or optional:
        lines.append("  needs:")
        lines += [f"    - job: {n}\n      artifacts: true" for n in (needs or ())]
        lines += [f"    - job: {n}\n      artifacts: true\n      optional: true" for n in optional]
    lines.append("  rules:")
    words = "|".join(skip or (name,))
    lines += [f"    - if: {_q(f'$SKIP_STAGES =~ /(^|[ ,])({words})([ ,]|$)/')}", "      when: never"]
    lines += [_scalar("    - if: ", c, "        ") + f"\n      when: {when}" for c in conditions]
    if artifacts:
        lines += ["  artifacts:", "    when: always", "    expire_in: 1 week", "    paths:"]
        lines += [f"      - {a}" for a in artifacts]
    lines.append("  script:")
    for block in python_blocks:
        lines += ["    - |", "      python3 - <<'PYEOF'"]
        lines += [f"      {row}" if row else "" for row in block.strip("\n").split("\n")]
        lines += ["      PYEOF"]
    lines += [f"    - python3 {HELPER} {s}" for s in script]
    return lines


def _cleanup_jobs() -> List[List[str]]:
    """initialization, every cleanup and its test, the Omnia cleanup, setup_main and its test."""
    jobs: List[List[str]] = [
        _job("initialization", "initialization", ["initialize"], [ANY_MODE], allow_failure=False,
             artifacts=[*COMMON_ARTIFACTS, "ci_tools/", "actual_commit_sha.txt"],
             python_blocks=[BOOTSTRAP]),
    ]
    previous: List[str] = []
    for domain in CLEANUP_ORDER:
        name = f"cleanup_{domain}"
        jobs.append(_job(name, name, [f"cleanup {domain}"],
                         [f"{CLEANUP_MODE} && {_domain_condition(domain)}"],
                         needs=["initialization"], optional=list(previous),
                         allow_failure=True, skip=(domain, name, "cleanup")))
        previous.append(name)
        name = f"test_cleanup_{domain}"
        jobs.append(_job(name, name, [f"cleanup-verify {domain}"],
                         [f"{CLEANUP_MODE} && {_domain_condition(domain)}"],
                         needs=["initialization"], optional=list(previous),
                         allow_failure=True, skip=(domain, name, "test_cleanup")))
        previous.append(name)
    jobs.append(_job("cleanup_omnia", "cleanup_omnia", ["cleanup-omnia"],
                     [f'{CLEANUP_MODE} && $DOMAINS == "default"'],
                     needs=["initialization"], optional=list(previous), allow_failure=True))
    jobs.append(_job("test_cleanup_omnia", "test_cleanup_omnia", ["cleanup-omnia-verify"],
                     [f'{CLEANUP_MODE} && $DOMAINS == "default"'],
                     needs=["initialization"], optional=[*previous, "cleanup_omnia"],
                     allow_failure=True, skip=("test_cleanup_omnia", "test_cleanup")))
    jobs.append(_job("setup_main", "setup_main", ["setup-main"],
                     ['$ENABLE_SETUP == "true"', DEPLOY_MODE]))
    jobs.append(_job("test_main_installation", "test_main_installation", ["verify main"],
                     [f'{DEPLOY_MODE} && $TEST_MODE == "true"'], allow_failure=True,
                     skip=("test_main_installation", "test")))
    return jobs


def _cluster_jobs() -> List[List[str]]:
    """The domain deploy stages and their tests of the cluster pipeline."""
    jobs: List[List[str]] = []
    for domain in DEPLOY_ORDER:
        extra = '$ENABLE_DISCOVERY == "true" && ' if domain == "discovery" else ""
        jobs.append(_job(domain, domain, [f"deploy {domain}"],
                         [f"{extra}{DEPLOY_MODE} && {_domain_condition(domain)}"],
                         skip=(domain, "deploy"), id_tokens=True))
        jobs.append(_job(f"test_{domain}", f"test_{domain}", [f"verify {domain}"],
                         [f'{extra}{DEPLOY_MODE} && $TEST_MODE == "true" && '
                          f"{_domain_condition(domain)}"], allow_failure=True,
                         skip=(domain, f"test_{domain}", "test"), id_tokens=True))
    return jobs


def _build_stream_jobs() -> List[List[str]]:
    """prepare_base, the tests of the base domains, build_stream and its test."""
    jobs = [_job("prepare_base", "prepare_base", ["prepare-base"],
                 [DEPLOY_MODE], skip=("prepare_base", "deploy"), id_tokens=True)]
    for domain in BASE_DOMAINS:
        jobs.append(_job(f"test_{domain}", f"test_{domain}", [f"verify {domain}"],
                         [f'{DEPLOY_MODE} && $TEST_MODE == "true" && {_domain_condition(domain)}'],
                         allow_failure=True, skip=(domain, f"test_{domain}", "test"),
                         id_tokens=True))
    jobs.append(_job("build_stream", "build_stream", ["deploy build_stream"],
                     [f"{DEPLOY_MODE} && {_domain_condition('build_stream')}"],
                     skip=("build_stream", "deploy"), id_tokens=True))
    jobs.append(_job("test_build_stream", "test_build_stream", ["verify build_stream"],
                     [f'{DEPLOY_MODE} && $TEST_MODE == "true" && '
                      f"{_domain_condition('build_stream')}"], allow_failure=True,
                     skip=("build_stream", "test_build_stream", "test"), id_tokens=True))
    return jobs


def _utils_jobs() -> List[List[str]]:
    """initialization, setup_utils, the utils modes and test_utils of the utils pipeline."""
    enabled = '$UTILS_ENABLE == "true"'
    jobs: List[List[str]] = [
        _job("initialization", "initialization", ["initialize"], [enabled], allow_failure=False,
             artifacts=[*COMMON_ARTIFACTS, "ci_tools/", "actual_commit_sha.txt"],
             python_blocks=[BOOTSTRAP]),
        _job("setup_utils", "setup_utils", ["setup-utils"], [enabled]),
    ]
    for name, tag in UTILS_TAGS.items():
        jobs.append(_job(name, name, ["deploy utils"], [UTILS_MODE_RULES[name]],
                         variables={"UTILS_TAGS": tag}, id_tokens=True,
                         skip=(name, "deploy")))
    jobs.append(_job("test_utils", "test_utils", ["verify utils"],
                     [f'{enabled} && $TEST_MODE == "true"'], allow_failure=True,
                     skip=("utils", "test_utils", "test"), id_tokens=True))
    return jobs




def _stages(kind: str) -> List[str]:
    """Return the stage names of a pipeline in order."""
    if kind == "utils":
        return ["initialization", "setup_utils", "install_os", "log_collection_cluster",
                "log_collection_oim", "test_utils", "summary"]
    cleanup = ["initialization",
               *(s for d in CLEANUP_ORDER for s in (f"cleanup_{d}", f"test_cleanup_{d}")),
               "cleanup_omnia", "test_cleanup_omnia", "setup_main", "test_main_installation"]
    if kind == "build_stream":
        return [*cleanup, "prepare_base", *(f"test_{d}" for d in BASE_DOMAINS), "build_stream",
                "test_build_stream", "summary"]
    return [*cleanup, *(s for d in DEPLOY_ORDER for s in (d, f"test_{d}")), "summary"]


INTRO_PARENT = """
# ---------------------------------------------------------------------------
# Omnia Parent Pipeline  (GENERATED by pipeline_render.py, do not edit)
# ---------------------------------------------------------------------------
# The first job, config, reads pipeline_config.yml of this commit with pipeline_triggers.py and
# writes generated-triggers.yml: one trigger job per cluster, for the cluster pipeline
# (.gitlab-ci-cluster.yml), the utils pipeline (.gitlab-ci-utils.yml, global.utils_enable) or the
# build stream pipeline (.gitlab-ci-build-stream.yml, global.build_stream_enable). The second job
# runs that file as a child pipeline, so the clusters run independently and in parallel; the
# pipeline fails when one of them fails.
#
# Change a setting by editing and committing pipeline_config.yml: no CI/CD variable has to be
# edited. A value that is empty in the file falls back to the CI/CD variable of the project with
# the old name (<CLUSTER>_PIPELINE_MODE, CLUSTERS, UTILS_ENABLE, ...), then to the default. The OIM
# password (<CLUSTER>_TARGET_PASS), the host key (<CLUSTER>_SSH_KNOWN_HOSTS), PIPELINE_API_TOKEN and
# the SMTP credentials stay CI/CD variables; the child pipelines inherit them.
#
# Layout of the project:
#   pipeline_config.yml                      clusters and settings (this pipeline reads it)
#   pipeline_triggers.py                     reads it and writes the trigger jobs
#   clusters/<name>/inputs/src/<domain>/     input files of every domain, src/main/omnia.env
#   clusters/<name>/inputs/test/<domain>/    optional test_config.yml and test_run_config.yml
# ---------------------------------------------------------------------------
"""


def _render_parent() -> str:
    """Return the text of .gitlab-ci.yml: generate the triggers, then run them."""
    rules = ["    - if: '$CI_PIPELINE_SOURCE == \"%s\"'\n      when: always" % source
             for source in ("schedule", "web", "api", "trigger", "parent_pipeline")]
    lines = [LICENSE + INTRO_PARENT, "workflow:", "  rules:", *rules, "", "stages:", "  - config",
             "  - trigger", "", "config:", "  stage: config", "  timeout: 10m",
             "  before_script: []", "  script:",
             "    - python3 pipeline_triggers.py --config pipeline_config.yml "
             "--out generated-triggers.yml", "  artifacts:", "    when: always",
             "    expire_in: 1 week", "    paths:", "      - generated-triggers.yml", "",
             "trigger_pipelines:", "  stage: trigger", "  trigger:", "    include:",
             "      - artifact: generated-triggers.yml", "        job: config",
             "    strategy: depend", ""]
    return "\n".join(lines)


def render(kind: str = "cluster") -> str:
    """Return the text of the pipeline file of ``kind`` (parent, cluster, build_stream, utils)."""
    if kind == "parent":
        return _render_parent()
    stages = _stages(kind)
    intro = {"cluster": INTRO, "build_stream": INTRO_BUILD_STREAM, "utils": INTRO_UTILS}[kind]
    out = [LICENSE + intro, "workflow:", "  rules:",
           "    - if: '$CI_PIPELINE_SOURCE == \"parent_pipeline\"'", "      when: always", "",
           "variables:"]
    out += [f"  {k}: {_q(v)}" for k, v in _variables(kind)]
    out += ["", "stages:"] + [f"  - {s}" for s in stages] + ["",
            "default:", "  retry:", "    max: 1", "    when:"]
    out += [f"      - {w}" for w in RETRY_WHEN]
    out += ["  before_script:", f"    - {_q(BEFORE_SCRIPT)}", "  after_script:"]
    out += [_scalar("    - ", a, "      ") for a in AFTER_SCRIPT]
    out += ["  artifacts:", "    when: always", "    expire_in: 1 week", "    paths:"]
    out += [f"      - {path}" for path in COMMON_ARTIFACTS] + [""]

    jobs: List[List[str]] = []
    if kind == "utils":
        jobs += _utils_jobs()
    else:
        jobs += _cleanup_jobs()
        if kind == "cluster":
            jobs += _cluster_jobs()
        else:
            jobs += _build_stream_jobs()
    summary = _job("summary", "summary", ["summary"], [ANY_MODE], when="always",
                   python_blocks=[SUMMARY_FALLBACK],
                   optional=[name for name in stages if name != "summary"],
                   allow_failure=False, artifacts=[*COMMON_ARTIFACTS, "pipeline_report/"],
                   variables={"PIPELINE_JOB_ORDER": ",".join(s for s in stages if s != "summary")})
    jobs.append(summary)
    for lines in jobs:
        out += lines + [""]
    return "\n".join(out)


def main(argv: List[str]) -> int:
    if argv == ["--write"]:
        for kind in KINDS:
            with open(OUTPUTS[kind], "w", encoding="utf-8") as handle:
                handle.write(render(kind))
            print(f"wrote {OUTPUTS[kind]}")
        return 0
    if argv == ["--check"]:
        stale = []
        for kind in KINDS:
            with open(OUTPUTS[kind], encoding="utf-8") as handle:
                if handle.read() != render(kind):
                    stale.append(OUTPUTS[kind])
        print("up to date" if not stale else f"{', '.join(stale)} differ: run pipeline_render.py --write")
        return 1 if stale else 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

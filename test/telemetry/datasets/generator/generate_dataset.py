"""
Telemetry Dataset Generator.

Generates test datasets from Jinja2 templates and variable profiles.

Usage:
    python generate_dataset.py <dataset_name> <profile>
    python generate_dataset.py <dataset_name> <profile> --var key=value
    python generate_dataset.py <dataset_name> --from-src
    python generate_dataset.py --list-profiles
"""

import argparse
import os
import shutil
import sys

import yaml
from jinja2 import Environment, FileSystemLoader

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PROFILES_DIR = os.path.join(SCRIPT_DIR, "profiles")
TEMPLATES_DIR = os.path.join(SCRIPT_DIR, "templates")
DATASETS_DIR = os.path.dirname(SCRIPT_DIR)
SRC_INPUT_DIR = os.path.join(
    os.path.dirname(os.path.dirname(os.path.dirname(SCRIPT_DIR))),
    "src", "telemetry", "input",
)


def list_profiles():
    """List available variable profiles."""
    print("Available profiles:")
    for f in sorted(os.listdir(PROFILES_DIR)):
        if f.endswith(".yml"):
            name = f.replace(".yml", "")
            print(f"  {name}")


def load_profile(profile_name):
    """Load a profile, merging defaults first."""
    # Always load defaults first
    defaults_path = os.path.join(PROFILES_DIR, "defaults.yml")
    with open(defaults_path, "r") as f:
        variables = yaml.safe_load(f) or {}

    # Overlay the profile
    if profile_name != "defaults":
        profile_path = os.path.join(PROFILES_DIR, f"{profile_name}.yml")
        if not os.path.isfile(profile_path):
            print(f"Error: Profile not found: {profile_path}")
            sys.exit(1)
        with open(profile_path, "r") as f:
            overlay = yaml.safe_load(f) or {}
        variables.update(overlay)

    return variables


def generate_dataset(name, variables):
    """Generate dataset from templates."""
    dest_dir = os.path.join(DATASETS_DIR, name)
    if os.path.exists(dest_dir):
        print(f"Warning: Dataset '{name}' already exists, overwriting...")
        shutil.rmtree(dest_dir)

    # Create output directories
    input_dir = os.path.join(dest_dir, "input")
    os.makedirs(input_dir, exist_ok=True)

    # Render templates (YAML config output — no HTML, XSS not applicable)
    env = Environment(  # nosec B701
        loader=FileSystemLoader(TEMPLATES_DIR),
        keep_trailing_newline=True,
        autoescape=False,
    )

    for template_rel in _find_templates(TEMPLATES_DIR):
        template = env.get_template(template_rel)
        rendered = template.render(**variables)

        # Remove .j2 suffix
        output_rel = template_rel.replace(".j2", "")
        output_path = os.path.join(dest_dir, output_rel)
        os.makedirs(os.path.dirname(output_path), exist_ok=True)
        with open(output_path, "w") as f:
            f.write(rendered)
        print(f"  Generated: {output_rel}")

    # Write README
    readme_path = os.path.join(dest_dir, "README.md")
    with open(readme_path, "w") as f:
        f.write(f"# Dataset: {name}\n\n")
        f.write("Auto-generated by `generate_dataset.py`.\n\n")
        f.write("## Variables\n\n")
        for key, val in sorted(variables.items()):
            f.write(f"- `{key}`: `{val}`\n")

    print(f"\nDataset created: {dest_dir}")


def copy_from_src(name):
    """Copy dataset from src/telemetry/input/."""
    dest_dir = os.path.join(DATASETS_DIR, name, "input")
    os.makedirs(dest_dir, exist_ok=True)

    if not os.path.isdir(SRC_INPUT_DIR):
        print(f"Error: Source input dir not found: {SRC_INPUT_DIR}")
        sys.exit(1)

    for f in os.listdir(SRC_INPUT_DIR):
        src = os.path.join(SRC_INPUT_DIR, f)
        if os.path.isfile(src):
            shutil.copy2(src, dest_dir)
            print(f"  Copied: {f}")

    print(f"\nDataset created from src: {os.path.join(DATASETS_DIR, name)}")


def _find_templates(base_dir):
    """Find all .j2 template files recursively."""
    templates = []
    for root, _, files in os.walk(base_dir):
        for f in files:
            if f.endswith(".j2"):
                rel = os.path.relpath(os.path.join(root, f), base_dir)
                templates.append(rel)
    return sorted(templates)


def main():
    parser = argparse.ArgumentParser(
        description="Telemetry dataset generator",
    )
    parser.add_argument("name", nargs="?", help="Dataset name")
    parser.add_argument("profile", nargs="?", default="defaults",
                        help="Variable profile name")
    parser.add_argument("--from-src", action="store_true",
                        help="Copy from src/telemetry/input/")
    parser.add_argument("--list-profiles", action="store_true",
                        help="List available profiles")
    parser.add_argument("--var", action="append", default=[],
                        help="Variable override: key=value")

    args = parser.parse_args()

    if args.list_profiles:
        list_profiles()
        return

    if not args.name:
        parser.print_help()
        sys.exit(1)

    if args.from_src:
        copy_from_src(args.name)
        return

    # Load profile and apply overrides
    variables = load_profile(args.profile)
    for var in args.var:
        key, _, val = var.partition("=")
        if val.lower() in ("true", "false"):
            val = val.lower() == "true"
        variables[key] = val

    generate_dataset(args.name, variables)


if __name__ == "__main__":
    main()

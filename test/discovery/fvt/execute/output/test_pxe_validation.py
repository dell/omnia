"""
Discovery — PXE Mapping Validation Tests.

These tests verify the data quality and format of the PXE mapping CSV
generated by the discovery playbook.

Test Cases:
- DISCOVERY_FVT_EXECUTE_V007: Verify all functional groups follow Omnia 2.3 pattern
- DISCOVERY_FVT_EXECUTE_V008: Verify ADMIN_IP/IB_IPV4 correlation with BMC_IP
- DISCOVERY_FVT_EXECUTE_V009: Verify PARENT_SERVICE_TAG (optional - validate if present)
- DISCOVERY_FVT_EXECUTE_V014: Verify PXE mapping CSV format for Orchestrator
"""

import pytest

from library.functions import (
    TestLogger,
    check_functional_groups_supported,
    check_ip_correlation,
    check_parent_service_tag,
    check_pxe_mapping_orchestrator_contract,
)
from library.messages import (
    TEST_NAMES,
    TEST_LOG_MSGS as LOG,
)
from library.vars.test_case_vars import TEST_CASES as TC


@pytest.mark.functional
@pytest.mark.order(7)
def test_functional_groups_supported(host):
    """DISCOVERY_FVT_EXECUTE_V007: Verify all functional groups follow Omnia 2.3 pattern.

    In Omnia 2.3, ALL functional groups MUST follow the pattern:
        <any_prefix>_rhel_<major>_<minor>_<arch>

    The prefix can be ANY string. The mandatory suffix is:
        _rhel_<major>_<minor>_(x86_64|aarch64)

    Valid examples:
        slurm_control_node_rhel_10_2_x86_64   ✅
        slurm_node_rhel_10_2_x86_64           ✅
        os_rhel_10_2_x86_64                   ✅
        sujal_rhel_10_0_x86_64                ✅ (custom prefix allowed)
        my_custom_group_rhel_9_4_aarch64      ✅ (any prefix allowed)

    Invalid examples:
        slurm_node_rocky_9_4_aarch64          ❌ (only rhel supported)
        slurm_node_x86_64                     ❌ (missing _rhel_<version>_)
    """
    tc = TC["functional_groups_supported"]
    tl = TestLogger(TEST_NAMES["functional_groups_supported"], tc["id"])
    result = check_functional_groups_supported(host)

    if result["success"]:
        tl.passed(LOG["functional_groups_ok"], result["details"])
    else:
        tl.failed(
            LOG["functional_groups_unsupported"].format(
                groups=", ".join(result.get("unsupported_groups", []))
            ),
            result["details"]
        )

    assert result["success"], result["error"]



    if result.get("skipped"):
        tl.passed(LOG["parent_service_tag_skipped"], result["details"])
    elif result["success"]:
        tl.passed(LOG["parent_service_tag_ok"], result["details"])
    else:
        tl.failed(
            LOG["parent_service_tag_failed"].format(
                count=len(result.get("invalid_rows", []))
            ),
            result["details"]
        )

    assert result["success"], result["error"]



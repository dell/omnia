"""
Discovery — IB and PXE Mapping Column Validation Tests.

These tests verify InfiniBand IP assignment data quality and the full
12-column output contract of the PXE mapping CSV generated by discovery.

Test Cases:
- DISCOVERY_FVT_EXECUTE_V016: Verify IB columns populated consistently with IB_NIC_NAME
- DISCOVERY_FVT_EXECUTE_V017: Verify IB_IPV4 values are valid IPv4 addresses
- DISCOVERY_FVT_EXECUTE_V018: Verify IB_IPV6 values are valid IPv6 addresses
- DISCOVERY_FVT_EXECUTE_V019: Verify IB IP addresses are unique across PXE mapping
- DISCOVERY_FVT_EXECUTE_V020: Verify all 12 output contract columns present
- DISCOVERY_FVT_EXECUTE_V021: Verify BMC_MAC populated for every row
"""

import pytest

from library.functions import (
    TestLogger,
    check_ib_conditional_population,
    check_ib_ipv4_format,
    check_ib_ipv6_format,
    check_ib_ip_uniqueness,
    check_pxe_mapping_all_columns,
    check_bmc_mac_populated,
)
from library.messages import (
    TEST_NAMES,
    TEST_LOG_MSGS as LOG,
)
from library.vars.test_case_vars import TEST_CASES as TC


@pytest.mark.functional
@pytest.mark.order(16)
def test_ib_conditional_population(host):
    """DISCOVERY_FVT_EXECUTE_V016: Verify IB columns populated consistently.

    Skips when no IB subnet is configured in network_spec.yml.
    Rows WITH IB_NIC_NAME must have IB_IPV4 (if ib_subnet configured)
    and IB_IPV6 (if ipv6_subnet configured).
    Rows WITHOUT IB_NIC_NAME must have empty IB_IPV4 and IB_IPV6.
    """
    tc = TC["ib_conditional_population"]
    tl = TestLogger(TEST_NAMES["ib_conditional_population"], tc["id"])
    result = check_ib_conditional_population(host)

    if result.get("skipped"):
        tl.skipped(LOG["ib_skipped"], result["details"])
        pytest.skip(result["details"])

    if result["success"]:
        tl.passed(LOG["ib_conditional_ok"], result["details"])
    else:
        tl.failed(
            LOG["ib_conditional_failed"].format(
                count=len(result.get("invalid_rows", []))
            ),
            result["details"]
        )

    assert result["success"], result["error"]


